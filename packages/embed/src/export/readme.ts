import type { CompiledTour } from '@sothspell/core';
import type { EmbedManifest } from './manifest.js';

const FENCE = '```';

function formatBytes(bytes: number): string {
  if (bytes < 1024) {
    return `${bytes} B`;
  }
  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1)} KiB`;
  }
  return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
}

/**
 * The bundle README is the audit document a reviewer reads before publishing:
 * exactly which files ship, the embed snippet for both integration styles, and
 * what the player stores and sends (nothing).
 */
export function renderExportReadme(
  tour: CompiledTour,
  manifest: EmbedManifest,
  generatedAt: string,
): string {
  const revision = `${tour.project.name} at ${tour.project.revision.commit}`;
  const fileRows = manifest.files
    .map(
      (file) => `| \`${file.path}\` | ${formatBytes(file.bytes)} | \`${file.sha256}\` |`,
    )
    .join('\n');

  return [
    `# ${tour.title} — Sóþspell embed bundle`,
    '',
    `Generated by \`sothspell export --embed\` on ${generatedAt} from tour`,
    `\`${tour.id}\` (schema ${tour.schemaVersion}), pinned to ${revision}.`,
    '',
    '## What ships',
    '',
    '| File | Size | SHA-256 |',
    '| --- | ---: | --- |',
    fileRows,
    '',
    '`export-manifest.json` lists every shipped file — including this README —',
    'with its byte size and SHA-256. Only the manifest itself is absent, because',
    'it cannot hash itself. `tour.json` embeds',
    `${manifest.excerpts.count} code excerpts (${formatBytes(manifest.excerpts.totalBytes)} of`,
    `source text) and the narration. The full repository does not ship, and the`,
    'export rejects machine-specific absolute paths and secret-shaped values.',
    '',
    '- `player.js` is a self-contained ES module; it has no API client, no',
    '  database, no Node built-ins, and no provider code.',
    '- `player.css` only carries host-page defaults (sizing and the iframe page);',
    '  the player styles live inside the element shadow root.',
    '- `embed.html` is the iframe host page, with no inline scripts.',
    '',
    '## Custom element',
    '',
    FENCE + 'html',
    '<link rel="stylesheet" href="./sothspell/player.css" />',
    '<script type="module" src="./sothspell/player.js"></script>',
    '',
    '<sothspell-tour',
    '  tour="./sothspell/tour.json"',
    '  locale="en"',
    '  progress="on"',
    '  style="min-height: 420px"',
    '></sothspell-tour>',
    FENCE,
    '',
    'Methods (also available on `window.SothspellEmbed`):',
    '',
    '| Method | Purpose |',
    '| --- | --- |',
    '| `load(tourUrl)` | Load (or replace) the tour. |',
    '| `play()` / `pause()` / `toggle()` | Control playback. |',
    '| `seek(fraction)` | Seek to a fraction of the whole tour (0–1). |',
    '| `seekToBeat(beatId)` | Seek to a known beat. |',
    '| `setSpeed(speed)` | Playback speed, 0.5–3. |',
    '| `next()` / `previous()` | Move one beat. |',
    '| `setLocale(locale)` | Switch to a shipped translation, or `null` for the source. |',
    '| `setProgressEnabled(enabled)` | Toggle local progress at runtime. |',
    '',
    'Events bubble and cross the shadow boundary; `event.detail` is the player',
    'snapshot (or `{ message }` for `sothspell:error`):',
    '',
    '| Event | When |',
    '| --- | --- |',
    '| `sothspell:ready` | The tour loaded. |',
    '| `sothspell:progress` | Position, status, or speed changed (about four times a second while playing). |',
    '| `sothspell:complete` | The tour finished; stored progress is cleared. |',
    '| `sothspell:error` | Load or playback failed; `detail.message` explains. |',
    '',
    '## Iframe fallback',
    '',
    'The iframe is the isolation option: the same bundle runs inside its own',
    'document and speaks `postMessage`. Host-side helper:',
    '',
    FENCE + 'js',
    "import { createIframeEmbed } from './sothspell/player.js';",
    '',
    'const embed = createIframeEmbed({',
    "  src: './sothspell/embed.html',",
    "  tour: './sothspell/tour.json',",
    '  height: 480,',
    "  title: 'Sóþspell tour',",
    '  onEvent: (message) => console.log(message.type, message.payload),',
    '});',
    "document.querySelector('#tour-slot').append(embed.element);",
    FENCE,
    '',
    'Or plain HTML; the `tour` parameter is resolved by `embed.html`, so it is',
    'relative to the bundle directory:',
    '',
    FENCE + 'html',
    '<iframe',
    '  src="./sothspell/embed.html?tour=./tour.json&progress=on"',
    '  title="Sóþspell tour"',
    '  style="width: 100%; height: 480px; border: 0"',
    '></iframe>',
    FENCE,
    '',
    `Messages use the channel \`${manifest.embed.channel}\`; commands from the`,
    'host are `{ channel, type, payload }` with `load`, `play`, `pause`,',
    '`toggle`, `seek`, `next`, `previous`, `locale`, and `destroy`.',
    '',
    '## Progress and privacy',
    '',
    `- Progress is stored under \`sothspell:embed:${tour.id}\` in the host`,
    '  origin `localStorage`. Nothing leaves the page.',
    '- Set `progress="off"` (or call `setProgressEnabled(false)`) to disable it;',
    '  any stored record for the tour is cleared.',
    '- Narration is browser speech only; the embed makes no network calls and',
    '  needs no provider keys. Cloud narration is out of scope for the embed.',
    '- A stale-anchor check cannot run without the repository; the footer shows',
    `  the pinned revision (${tour.project.revision.commit}) instead.`,
    '',
    '## Content Security Policy',
    '',
    'No inline scripts and no external origins are required:',
    '',
    FENCE,
    "Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self'",
    FENCE,
    '',
    'Serve the bundle from the same origin as the docs page (or allow that',
    'origin in `script-src`/`style-src` if you host it separately).',
    '',
  ].join('\n');
}
